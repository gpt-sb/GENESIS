def select_compounds():
    """Select top 25 generated + top 25 repurposed from Phase 7 results."""
    print("\n" + "=" * 70)
    print("PHASE A: Compound Selection")
    print("=" * 70)

    df = pd.read_csv(PHASE7_RESULTS, sep="\t")
    valid = df.dropna(subset=["best_energy_kcal"])
    print(f"  Phase 7 results: {len(valid)} valid docks")

    # Top 25 generated by best docking energy
    gen = valid[valid["source"] == "generated"].nsmallest(TOP_N_GEN, "best_energy_kcal")
    rep = valid[valid["source"] == "repurposed"].nsmallest(TOP_N_REP, "best_energy_kcal")

    compounds = []
    seen_smiles = set()

    for _, row in pd.concat([gen, rep]).iterrows():
        smi = row["smiles"]
        if smi in seen_smiles:
            continue
        seen_smiles.add(smi)
        compounds.append({
            "cpd_id": row["cpd_id"],
            "smiles": smi,
            "source": row["source"],
            "method": row.get("method", ""),
            "compound_name": row.get("compound_name", ""),
            "original_target": row["target"],
            "original_energy": row["best_energy_kcal"],
            "composite_score": row.get("composite_score", 0),
            "vp_similarity": row.get("vp_similarity", 0),
            "recommendation_weight": row.get("recommendation_weight", 0),
            "overall_flag": row.get("overall_flag", ""),
        })

    print(f"  Selected {len(compounds)} unique compounds:")
    n_gen = sum(1 for c in compounds if c["source"] == "generated")
    n_rep = sum(1 for c in compounds if c["source"] == "repurposed")
    print(f"    Generated:  {n_gen}")
    print(f"    Repurposed: {n_rep}")
    print(f"  Energy range: {min(c['original_energy'] for c in compounds):.1f} "
          f"to {max(c['original_energy'] for c in compounds):.1f} kcal/mol")

    return compounds


