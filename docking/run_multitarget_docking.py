def analyze_multitarget(df):
    """Comprehensive multi-target binding analysis."""
    from scipy.stats import spearmanr

    print("\n" + "=" * 70)
    print("PHASE D: Multi-Target Analysis")
    print("=" * 70)

    valid = df.dropna(subset=["best_energy_kcal"])
    print(f"\n  Valid results: {len(valid)}/{len(df)}")

    # ── 1. Overall energy distribution across all targets ──
    energies = valid["best_energy_kcal"]
    print(f"\n  === Overall Energy Distribution (All-vs-All) ===")
    print(f"  Mean: {energies.mean():.1f}, Median: {energies.median():.1f}, "
          f"Best: {energies.min():.1f}, SD: {energies.std():.1f}")
    for thresh in [-6, -7, -8, -9, -10]:
        n = (energies <= thresh).sum()
        print(f"    ≤ {thresh}: {n} ({n*100/len(energies):.1f}%)")

    # ── 2. Per-target summary ──
    print(f"\n  === Per-Target Summary ===")
    target_stats = []
    for target in sorted(valid["target"].unique()):
        te = valid[valid["target"] == target]["best_energy_kcal"]
        stats = {
            "target": target,
            "pdb_id": TARGETS[target]["pdb_id"],
            "n": len(te),
            "mean": round(te.mean(), 1),
            "median": round(te.median(), 1),
            "best": round(te.min(), 1),
            "sd": round(te.std(), 1),
            "n_le7": int((te <= -7).sum()),
            "n_le8": int((te <= -8).sum()),
            "n_le9": int((te <= -9).sum()),
            "hit_rate_7": round((te <= -7).sum() * 100 / len(te), 1),
        }
        target_stats.append(stats)
        print(f"  {target:8s}: n={stats['n']:3d}, mean={stats['mean']:.1f}, "
              f"best={stats['best']:.1f}, ≤-7: {stats['n_le7']} ({stats['hit_rate_7']:.0f}%), "
              f"≤-8: {stats['n_le8']}, ≤-9: {stats['n_le9']}")

    # ── 3. Multi-target binder identification ──
    print(f"\n  === Multi-Target Binders ===")
    mt_results = {}
    for thresh_label, thresh in [("≤-6.0", -6.0), ("≤-7.0", -7.0), ("≤-8.0", -8.0)]:
        hits = valid[valid["best_energy_kcal"] <= thresh]
        cpd_targets = hits.groupby("cpd_id").agg(
            n_targets=("target", "nunique"),
            targets=("target", lambda x: ", ".join(sorted(x.unique()))),
            best_energy=("best_energy_kcal", "min"),
            mean_energy=("best_energy_kcal", "mean"),
            source=("source", "first"),
            smiles=("smiles", "first"),
        ).reset_index()

        n_multi = {}
        for min_tgt in [2, 3, 4, 5]:
            m = cpd_targets[cpd_targets["n_targets"] >= min_tgt]
            n_multi[min_tgt] = len(m)

        print(f"  At {thresh_label}: ≥2 targets: {n_multi[2]}, ≥3: {n_multi[3]}, "
              f"≥4: {n_multi[4]}, ≥5: {n_multi[5]}")

        mt_results[thresh_label] = {
            "threshold": thresh,
            "multi2": n_multi[2],
            "multi3": n_multi[3],
            "multi4": n_multi[4],
            "multi5": n_multi[5],
        }

    # ── 4. Detailed multi-target binder table ──
    # Primary threshold: ≤-7.0 against ≥2 targets
    hits7 = valid[valid["best_energy_kcal"] <= -7.0]
    binder_df = hits7.groupby("cpd_id").agg(
        n_targets=("target", "nunique"),
        targets=("target", lambda x: ", ".join(sorted(x.unique()))),
        best_energy=("best_energy_kcal", "min"),
        mean_energy=("best_energy_kcal", "mean"),
        source=("source", "first"),
        smiles=("smiles", "first"),
        method=("method", "first"),
        compound_name=("compound_name", "first"),
        original_target=("original_target", "first"),
        composite_score=("composite_score", "first"),
        vp_similarity=("vp_similarity", "first"),
        overall_flag=("overall_flag", "first"),
    ).reset_index()

    multi_binders = binder_df[binder_df["n_targets"] >= 2].sort_values(
        ["n_targets", "best_energy"], ascending=[False, True]
    )

    if len(multi_binders) > 0:
        print(f"\n  === Multi-Target Binders (≤-7.0, ≥2 targets) ===")
        print(f"  Total: {len(multi_binders)} compounds")
        for _, r in multi_binders.iterrows():
            name = r.get("compound_name", "") or r.get("method", "")
            print(f"    {r['cpd_id']:30s} [{r['source']:10s}] "
                  f"{r['n_targets']} targets ({r['targets']}), "
                  f"best={r['best_energy']:.1f}, mean={r['mean_energy']:.1f}  {name}")

        multi_binders.to_csv(MT_BINDERS, sep="\t", index=False)
        print(f"  Saved: {MT_BINDERS.name}")

    # ── 5. Selectivity profiles ──
    print(f"\n  === Selectivity Profiles ===")
    profiles = []
    for cpd_id in valid["cpd_id"].unique():
        cpd_data = valid[valid["cpd_id"] == cpd_id]
        row = {"cpd_id": cpd_id}
        row["source"] = cpd_data["source"].iloc[0]
        row["method"] = cpd_data["method"].iloc[0]
        row["smiles"] = cpd_data["smiles"].iloc[0]
        row["compound_name"] = cpd_data.get("compound_name", pd.Series([""])).iloc[0]
        row["composite_score"] = cpd_data["composite_score"].iloc[0]
        row["overall_flag"] = cpd_data.get("overall_flag", pd.Series([""])).iloc[0]

        for target in TARGETS:
            tgt_val = cpd_data[cpd_data["target"] == target]["best_energy_kcal"]
            row[f"dG_{target}"] = round(tgt_val.iloc[0], 1) if len(tgt_val) > 0 else None

        # Compute selectivity metrics
        tgt_energies = [row[f"dG_{t}"] for t in TARGETS if row.get(f"dG_{t}") is not None]
        row["n_docked"] = len(tgt_energies)
        row["best_energy"] = min(tgt_energies) if tgt_energies else None
        row["mean_energy"] = round(np.mean(tgt_energies), 1) if tgt_energies else None
        row["energy_sd"] = round(np.std(tgt_energies), 2) if len(tgt_energies) > 1 else None
        row["n_hits_le7"] = sum(1 for e in tgt_energies if e <= -7.0)
        row["n_hits_le8"] = sum(1 for e in tgt_energies if e <= -8.0)

        # Selectivity index: SD of energies (higher = more selective)
        if row["energy_sd"] is not None:
            row["selectivity_index"] = row["energy_sd"]
        else:
            row["selectivity_index"] = None

        # Best target
        if tgt_energies:
            best_tgt = min(TARGETS.keys(), key=lambda t: row.get(f"dG_{t}", 0) or 0)
            row["best_target"] = best_tgt
        else:
            row["best_target"] = None

        profiles.append(row)

    prof_df = pd.DataFrame(profiles)
    prof_df = prof_df.sort_values("best_energy", ascending=True)
    prof_df.to_csv(SELECTIVITY, sep="\t", index=False)
    print(f"  Saved selectivity profiles: {SELECTIVITY.name} ({len(prof_df)} compounds)")

    # Classify compounds
    n_selective = (prof_df["n_hits_le7"] == 1).sum()
    n_dual = (prof_df["n_hits_le7"] == 2).sum()
    n_broad = (prof_df["n_hits_le7"] >= 3).sum()
    n_weak = (prof_df["n_hits_le7"] == 0).sum()
    print(f"  Selectivity breakdown (at ≤-7.0):")
    print(f"    Selective (1 target): {n_selective}")
    print(f"    Dual binders (2):     {n_dual}")
    print(f"    Broad (≥3):           {n_broad}")
    print(f"    Weak (<-7 on none):   {n_weak}")

    # ── 6. Polypharmacology network ──
    print(f"\n  === Polypharmacology Network ===")
    # For each pair of targets, count compounds that hit both at ≤-7.0
    target_list = sorted(TARGETS.keys())
    network = []
    for i, t1 in enumerate(target_list):
        for j, t2 in enumerate(target_list):
            if j <= i:
                continue
            # Compounds hitting both
            col1, col2 = f"dG_{t1}", f"dG_{t2}"
            dual = prof_df[
                (prof_df[col1].notna()) & (prof_df[col1] <= -7.0) &
                (prof_df[col2].notna()) & (prof_df[col2] <= -7.0)
            ]
            if len(dual) > 0:
                network.append({
                    "target_1": t1,
                    "target_2": t2,
                    "n_shared_binders": len(dual),
                    "compound_ids": ", ".join(dual["cpd_id"].tolist()[:10]),
                    "mean_energy_t1": round(dual[col1].mean(), 1),
                    "mean_energy_t2": round(dual[col2].mean(), 1),
                })
                print(f"  {t1:8s} — {t2:8s}: {len(dual)} shared binders")

    if network:
        net_df = pd.DataFrame(network).sort_values("n_shared_binders", ascending=False)
        net_df.to_csv(POLYP_NETWORK, sep="\t", index=False)
        print(f"  Saved polypharmacology network: {POLYP_NETWORK.name}")
    else:
        print("  No shared binders found between any target pair")

    # ── 7. Pathway-aware dual binders ──
    print(f"\n  === Pathway-Aware Analysis ===")
    pathways = {
        "PI3K/AKT/mTOR": ["AKT1", "PIK3CA", "MTOR"],
        "RTK (EGFR+FGFR1)": ["EGFR", "FGFR1"],
        "Apoptosis (MDM2+PTGS2)": ["MDM2", "PTGS2"],
    }
    for pw_name, pw_targets in pathways.items():
        pw_cols = [f"dG_{t}" for t in pw_targets]
        # Compounds hitting ≥2 pathway targets at ≤-7.0
        pw_hits = prof_df.copy()
        pw_hits["pw_n_hits"] = sum(
            (pw_hits[c].notna() & (pw_hits[c] <= -7.0)).astype(int) for c in pw_cols
        )
        dual_pw = pw_hits[pw_hits["pw_n_hits"] >= 2]
        if len(dual_pw) > 0:
            print(f"  {pw_name}: {len(dual_pw)} dual pathway binders")
            for _, r in dual_pw.head(5).iterrows():
                vals = ", ".join(f"{t}={r.get(f'dG_{t}', '?')}" for t in pw_targets)
                print(f"    {r['cpd_id']:30s} [{r['source']}] {vals}")
        else:
            print(f"  {pw_name}: no dual pathway binders")

    # ── 8. Top compounds overall ──
    print(f"\n  === Top 15 Compounds by Best Energy (across all targets) ===")
    for _, r in prof_df.head(15).iterrows():
        name = r.get("compound_name", "") or r.get("method", "")
        tgt_scores = []
        for t in target_list:
            e = r.get(f"dG_{t}")
            if e is not None and e <= -7.0:
                tgt_scores.append(f"{t}:{e:.1f}")
        print(f"  {r['cpd_id']:30s} [{r['source']:10s}] "
              f"best={r['best_energy']:.1f}, hits={r['n_hits_le7']}/7  "
              f"{', '.join(tgt_scores)}  {name}")

    # ── 9. Source comparison for multi-target binding ──
    print(f"\n  === Source Comparison (Multi-Target) ===")
    for src in ["generated", "repurposed"]:
        sub = prof_df[prof_df["source"] == src]
        if len(sub) > 0:
            print(f"  {src:12s}: n={len(sub)}, mean_best={sub['best_energy'].mean():.1f}, "
                  f"mean_n_hits={sub['n_hits_le7'].mean():.1f}, "
                  f"dual_binders={int((sub['n_hits_le7'] >= 2).sum())}, "
                  f"broad_binders={int((sub['n_hits_le7'] >= 3).sum())}")

    # Build summary
    summary = {
        "phase": "7b",
        "description": "Multi-Target Docking Validation",
        "n_compounds": len(prof_df),
        "n_targets": len(TARGETS),
        "targets_used": target_list,
        "total_jobs": len(df),
        "successful_docks": len(valid),
        "failed_docks": len(df) - len(valid),
        "energy_stats": {
            "mean": round(energies.mean(), 2),
            "median": round(energies.median(), 2),
            "best": round(energies.min(), 2),
            "sd": round(energies.std(), 2),
        },
        "multitarget_binders": {
            thresh_label: mt_results[thresh_label]
            for thresh_label in mt_results
        },
        "selectivity_breakdown": {
            "selective_1": int(n_selective),
            "dual_2": int(n_dual),
            "broad_ge3": int(n_broad),
            "weak_0": int(n_weak),
        },
        "polypharmacology_edges": len(network),
        "source_comparison": {
            src: {
                "n": int(len(prof_df[prof_df["source"] == src])),
                "mean_best_energy": round(prof_df[prof_df["source"] == src]["best_energy"].mean(), 2)
                    if len(prof_df[prof_df["source"] == src]) > 0 else None,
                "mean_n_hits_le7": round(prof_df[prof_df["source"] == src]["n_hits_le7"].mean(), 2)
                    if len(prof_df[prof_df["source"] == src]) > 0 else None,
            }
            for src in ["generated", "repurposed"]
        },
        "per_target": target_stats,
    }

    with open(MT_SUMMARY, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"\n  Saved summary: {MT_SUMMARY.name}")

    return summary


