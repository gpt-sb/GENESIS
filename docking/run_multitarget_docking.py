def verify_inputs(compounds):
    """Verify all receptor and ligand PDBQT files exist."""
    print("\n" + "=" * 70)
    print("PHASE B: Input Verification")
    print("=" * 70)

    # Check receptors
    receptor_map = {}
    for target, info in TARGETS.items():
        pdbqt = REC_DIR / f"{info['pdb_id']}_receptor.pdbqt"
        if pdbqt.exists():
            receptor_map[target] = str(pdbqt)
            print(f"  [{target}] {pdbqt.name} OK ({pdbqt.stat().st_size // 1024} KB)")
        else:
            print(f"  [{target}] MISSING: {pdbqt}")

    # Check ligands
    ligand_map = {}
    n_ok, n_miss = 0, 0
    for c in compounds:
        pdbqt = LIG_DIR / f"{c['cpd_id']}.pdbqt"
        if pdbqt.exists() and pdbqt.stat().st_size > 50:
            ligand_map[c["cpd_id"]] = str(pdbqt)
            n_ok += 1
        else:
            n_miss += 1
            print(f"  MISSING ligand: {c['cpd_id']}")

    print(f"  Receptors: {len(receptor_map)}/{len(TARGETS)} OK")
    print(f"  Ligands: {n_ok}/{len(compounds)} OK, {n_miss} missing")

    return receptor_map, ligand_map


