def run_multitarget_docking(compounds, receptor_map, ligand_map):
    """Dock each compound against all 7 targets."""
    from vina import Vina

    print("\n" + "=" * 70)
    print("PHASE C: Multi-Target Docking Execution")
    print("=" * 70)

    POSES_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)

    # Build job list: each compound × each target
    jobs = []
    for c in compounds:
        cpd_id = c["cpd_id"]
        if cpd_id not in ligand_map:
            continue
        for target in TARGETS:
            if target not in receptor_map:
                continue
            jobs.append({
                "cpd_id": cpd_id,
                "smiles": c["smiles"],
                "source": c["source"],
                "method": c["method"],
                "compound_name": c.get("compound_name", ""),
                "target": target,
                "receptor_pdbqt": receptor_map[target],
                "ligand_pdbqt": ligand_map[cpd_id],
                "center": TARGETS[target]["center"],
                "size": TARGETS[target]["size"],
                "original_target": c["original_target"],
                "original_energy": c["original_energy"],
                "composite_score": c["composite_score"],
                "vp_similarity": c["vp_similarity"],
                "recommendation_weight": c["recommendation_weight"],
                "overall_flag": c.get("overall_flag", ""),
            })

    n_total = len(jobs)
    print(f"  Total docking jobs: {n_total} ({len(compounds)} compounds × {len(TARGETS)} targets)")

    # Check for already-completed jobs (resume support)
    completed = {}
    if MT_RESULTS.exists():
        prev = pd.read_csv(MT_RESULTS, sep="\t")
        for _, row in prev.iterrows():
            key = (row["cpd_id"], row["target"])
            if pd.notna(row.get("best_energy_kcal")):
                completed[key] = row.to_dict()
        if completed:
            print(f"  Resuming: {len(completed)} jobs already completed")

    all_results = []
    n_success, n_fail, n_skip = 0, 0, 0
    t_start = time.time()
    report_every = max(1, n_total // 20)

    for ji, job in enumerate(jobs):
        key = (job["cpd_id"], job["target"])

        # Skip already completed
        if key in completed:
            all_results.append(completed[key])
            n_skip += 1
            continue

        if (ji - n_skip) % report_every == 0:
            elapsed = time.time() - t_start
            done = n_success + n_fail
            rate = max(done, 1) / elapsed if elapsed > 0 else 1
            remaining = (n_total - n_skip - done) / rate if rate > 0 else 0
            print(f"  [{ji+1}/{n_total}] ({ji*100//max(1,n_total)}%) "
                  f"[{elapsed:.0f}s, ~{remaining:.0f}s left] "
                  f"{job['cpd_id']} vs {job['target']}")

        try:
            v = Vina(sf_name="vina", verbosity=0)
            v.set_receptor(job["receptor_pdbqt"])
            v.set_ligand_from_file(job["ligand_pdbqt"])
            v.compute_vina_maps(center=list(job["center"]),
                                box_size=list(job["size"]))
            v.dock(exhaustiveness=EXHAUSTIVENESS, n_poses=N_MODES)
            energies = v.energies()

            best_energy = round(float(energies[0][0]), 2)
            all_energies = "|".join(f"{float(row[0]):.1f}" for row in energies)
            n_poses = len(energies)

            # Save best pose
            pose_file = POSES_DIR / f"{job['cpd_id']}_vs_{job['target']}.pdbqt"
            v.write_poses(str(pose_file), n_poses=1, overwrite=True)
            n_success += 1

        except Exception as e:
            best_energy = None
            all_energies = ""
            n_poses = 0
            n_fail += 1
            if n_fail <= 10:
                print(f"    FAIL: {job['cpd_id']} vs {job['target']}: {e}")

        result = {
            "cpd_id": job["cpd_id"],
            "smiles": job["smiles"],
            "source": job["source"],
            "method": job["method"],
            "compound_name": job.get("compound_name", ""),
            "target": job["target"],
            "pdb_id": TARGETS[job["target"]]["pdb_id"],
            "best_energy_kcal": best_energy,
            "all_energies": all_energies,
            "n_poses": n_poses,
            "original_target": job["original_target"],
            "original_energy": job["original_energy"],
            "composite_score": job["composite_score"],
            "vp_similarity": job["vp_similarity"],
            "recommendation_weight": job["recommendation_weight"],
            "overall_flag": job.get("overall_flag", ""),
        }
        all_results.append(result)

        # Periodic save (every 50 jobs)
        if (n_success + n_fail) % 50 == 0 and (n_success + n_fail) > 0:
            pd.DataFrame(all_results).to_csv(MT_RESULTS, sep="\t", index=False)

    elapsed = time.time() - t_start
    print(f"\n  Multi-target docking complete:")
    print(f"    New docks: {n_success} OK, {n_fail} failed")
    print(f"    Resumed:   {n_skip} from previous run")
    print(f"    Total:     {len(all_results)} results in {elapsed:.1f}s")

    df = pd.DataFrame(all_results)
    df.to_csv(MT_RESULTS, sep="\t", index=False)
    print(f"  Saved: {MT_RESULTS.name}")

    return df


